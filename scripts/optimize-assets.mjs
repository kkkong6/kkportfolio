import sharp from 'sharp';
import {mkdir,writeFile,stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {art,portrait} from '../artwork-source.js';
import {clearEdgeBackground} from '../asset-renderer.js';

const output=new URL('../assets/optimized/',import.meta.url);
await mkdir(output,{recursive:true});
const manifest={};
let total=0;
async function encode(name,input,width,height,extra={}){
  const variants=[];
  for(const limit of [320,940]){
    const file=`${name}-${limit}.webp`;
    const result=await sharp(input).resize({width:limit,height:limit,fit:'inside',withoutEnlargement:true}).webp({quality:88,alphaQuality:100,effort:6}).toFile(fileURLToPath(new URL(file,output)));
    total+=result.size;
    variants.push({file,width:result.width});
  }
  return {width,height,variants,...extra};
}
for(const [id,states] of Object.entries(art)){
  manifest[id]={};
  for(const [state,asset] of Object.entries(states)){
    const [left,top,width,height]=asset.rect;
    const {data,info}=await sharp(fileURLToPath(asset.file))
      .resize(asset.size[0],asset.size[1],{fit:'fill'})
      .extract({left,top,width,height}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    if(asset.backdrop)clearEdgeBackground(data,width,height);
    const png=await sharp(data,{raw:{width,height,channels:info.channels}}).png().toBuffer();
    manifest[id][state]=await encode(`${id}-${state}`,png,width,height,{sprite:!!asset.sprite});
  }
}
const photo=await sharp(fileURLToPath(portrait)).metadata();
const portraitAsset=await encode('portrait',fileURLToPath(portrait),photo.width,photo.height);
for(const width of [640,1254]){
  const file=new URL(`bag-${width}.webp`,output);
  await sharp(fileURLToPath(new URL('../assets/bag-open-overhead.png',import.meta.url)))
    .resize({width,withoutEnlargement:true}).webp({quality:90,alphaQuality:100,effort:6}).toFile(fileURLToPath(file));
  total+=(await stat(file)).size;
}
await writeFile(new URL('../artwork-manifest.js',import.meta.url),
  `// Generated by npm run optimize:assets.\nexport const artwork = ${JSON.stringify(manifest,null,2)};\nexport const portraitAsset = ${JSON.stringify(portraitAsset,null,2)};\n`);
console.log(`Optimized artwork generated: ${(total/1024/1024).toFixed(2)} MiB across all sizes and states.`);
